import { afterEach, describe, expect, it } from 'vitest';
import type { Db } from '../../../db/types.js';
import { up, down } from '../../../db/migrations/20260819_000001_custom_model_tombstones.js';
import { createEmptyTestDb } from '../../helpers/test-db.js';

async function makeDb(): Promise<{ db: Db; cleanup: () => Promise<void> }> {
  const scratch = await createEmptyTestDb();
  await scratch.db.exec(`
    CREATE TABLE models (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      platform TEXT NOT NULL,
      model_id TEXT NOT NULL,
      endpoint_scope TEXT NOT NULL DEFAULT ''
    );
  `);
  await scratch.db.run("INSERT INTO models (platform, model_id, endpoint_scope) VALUES ('custom', 'model-a', 'http://relay:9999')");
  return scratch;
}

async function columnNames(db: Db, table: string): Promise<string[]> {
  return (await db.all(
    'SELECT column_name FROM information_schema.columns WHERE table_name = ? ORDER BY ordinal_position',
    [table],
  ) as { column_name: string }[]).map(c => c.column_name);
}

const cleanups: Array<() => Promise<void>> = [];
afterEach(async () => {
  for (const fn of cleanups.splice(0)) await fn();
});

describe('custom_model_tombstones migration (#926)', () => {
  it('creates the tombstone table keyed by (endpoint_scope, model_id)', async () => {
    const { db, cleanup } = await makeDb();
    cleanups.push(cleanup);
    await up(db);

    const cols = await columnNames(db, 'custom_model_tombstones');
    expect(cols).toContain('endpoint_scope');
    expect(cols).toContain('model_id');
    expect(cols).toContain('created_at');

    await db.run('INSERT INTO custom_model_tombstones (endpoint_scope, model_id) VALUES (?, ?)', ['http://relay:9999', 'model-a']);
    // The primary key rejects a duplicate for the same endpoint+model.
    await expect(
      db.run('INSERT INTO custom_model_tombstones (endpoint_scope, model_id) VALUES (?, ?)', ['http://relay:9999', 'model-a']),
    ).rejects.toThrow();
  });

  it('down drops the table and leaves existing data intact', async () => {
    const { db, cleanup } = await makeDb();
    cleanups.push(cleanup);
    await up(db);
    await db.run('INSERT INTO custom_model_tombstones (endpoint_scope, model_id) VALUES (?, ?)', ['http://relay:9999', 'model-a']);
    await down(db);

    const reg = await db.get('SELECT to_regclass(?) AS reg', ['custom_model_tombstones']) as { reg: string | null };
    expect(reg.reg).toBeNull();
    // The models table (and its data) survives a revert.
    const models = await db.get('SELECT COUNT(*) AS n FROM models') as { n: number };
    expect(models.n).toBe(1);
  });
});
