import { afterEach, describe, expect, it } from 'vitest';
import type { Db } from '../../../db/types.js';
import { up, down } from '../../../db/migrations/20260706_000002_custom_model_tool_support.js';
import { createEmptyTestDb } from '../../helpers/test-db.js';

// A minimal stand-in for the models table on an EMPTY scratch database so the
// data-only migration can be exercised without the full catalog seed.
async function makeDb(): Promise<{ db: Db; cleanup: () => Promise<void> }> {
  const scratch = await createEmptyTestDb();
  await scratch.db.exec(`
    CREATE TABLE models (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      platform TEXT NOT NULL,
      model_id TEXT NOT NULL,
      supports_tools INTEGER NOT NULL DEFAULT 0
    );
  `);
  await scratch.db.run('INSERT INTO models (platform, model_id, supports_tools) VALUES (?, ?, ?)', ['custom', 'qwen3:4b', 0]);          // the stuck-at-zero case (#470)
  await scratch.db.run('INSERT INTO models (platform, model_id, supports_tools) VALUES (?, ?, ?)', ['custom', 'llama3:8b', 1]);          // already tool-capable
  await scratch.db.run('INSERT INTO models (platform, model_id, supports_tools) VALUES (?, ?, ?)', ['groq', 'llama-3.3-70b', 0]);        // a catalog row that must NOT change
  return scratch;
}

async function toolsByModel(db: Db): Promise<Record<string, number>> {
  const rows = await db.all('SELECT model_id, supports_tools FROM models') as { model_id: string; supports_tools: number }[];
  return Object.fromEntries(rows.map(r => [r.model_id, r.supports_tools]));
}

const cleanups: Array<() => Promise<void>> = [];
afterEach(async () => {
  for (const fn of cleanups.splice(0)) await fn();
});

describe('custom_model_tool_support migration (#470)', () => {
  it('flips every custom model to tool-capable and leaves catalog rows alone', async () => {
    const { db, cleanup } = await makeDb();
    cleanups.push(cleanup);

    await up(db);

    expect(await toolsByModel(db)).toEqual({
      'qwen3:4b': 1,
      'llama3:8b': 1,
      'llama-3.3-70b': 0, // catalog row untouched
    });
  });

  it('is idempotent — a second up() produces the identical result', async () => {
    const { db, cleanup } = await makeDb();
    cleanups.push(cleanup);

    await up(db);
    const once = await toolsByModel(db);
    await up(db);
    const twice = await toolsByModel(db);

    expect(twice).toEqual(once);
  });

  it('down() reverses the backfill for custom rows only', async () => {
    const { db, cleanup } = await makeDb();
    cleanups.push(cleanup);

    await up(db);
    await down(db);

    expect(await toolsByModel(db)).toEqual({
      'qwen3:4b': 0,
      'llama3:8b': 0,
      'llama-3.3-70b': 0,
    });
  });
});
