import { afterEach, describe, expect, it } from 'vitest';
import type { Db } from '../../../db/types.js';
import { up, down } from '../../../db/migrations/20260802_000001_custom_endpoint_host_labels.js';
import { createEmptyTestDb } from '../../helpers/test-db.js';

// A minimal stand-in for api_keys on an EMPTY scratch database: the data-only
// migration only reads platform / label / base_url.
async function makeDb(): Promise<{ db: Db; cleanup: () => Promise<void> }> {
  const scratch = await createEmptyTestDb();
  await scratch.db.exec(`
    CREATE TABLE api_keys (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      platform TEXT NOT NULL,
      label TEXT,
      base_url TEXT
    );
  `);
  await scratch.db.run('INSERT INTO api_keys (platform, label, base_url) VALUES (?, ?, ?)', ['custom', 'Custom', 'http://127.0.0.1:11434/v1']);   // legacy default (#704)
  await scratch.db.run('INSERT INTO api_keys (platform, label, base_url) VALUES (?, ?, ?)', ['custom', 'Custom', 'http://192.168.1.50:8080/v1']); // …and its indistinguishable twin
  await scratch.db.run('INSERT INTO api_keys (platform, label, base_url) VALUES (?, ?, ?)', ['custom', 'Ollama box', 'http://127.0.0.1:1234/v1']);// operator's own name: untouched
  await scratch.db.run('INSERT INTO api_keys (platform, label, base_url) VALUES (?, ?, ?)', ['custom', 'Custom', null]);                          // no URL to rename to
  await scratch.db.run('INSERT INTO api_keys (platform, label, base_url) VALUES (?, ?, ?)', ['groq', 'Custom', null]);                            // catalog key that must NOT change
  return scratch;
}

async function labels(db: Db): Promise<(string | null)[]> {
  return (await db.all('SELECT label FROM api_keys ORDER BY id') as { label: string | null }[])
    .map(r => r.label);
}

const cleanups: Array<() => Promise<void>> = [];
afterEach(async () => {
  for (const fn of cleanups.splice(0)) await fn();
});

describe('custom_endpoint_host_labels migration (#704)', () => {
  it('renames the legacy default to the endpoint host and leaves everything else alone', async () => {
    const { db, cleanup } = await makeDb();
    cleanups.push(cleanup);

    await up(db);

    expect(await labels(db)).toEqual([
      '127.0.0.1:11434',
      '192.168.1.50:8080',
      'Ollama box',
      'Custom', // no base_url: nothing to rename to
      'Custom', // not a custom endpoint
    ]);
  });

  it('is idempotent — a second up() produces the identical result', async () => {
    const { db, cleanup } = await makeDb();
    cleanups.push(cleanup);

    await up(db);
    const once = await labels(db);
    await up(db);

    expect(await labels(db)).toEqual(once);
  });

  it('down() restores the generic label on the endpoints up() renamed', async () => {
    const { db, cleanup } = await makeDb();
    cleanups.push(cleanup);

    await up(db);
    await down(db);

    expect(await labels(db)).toEqual(['Custom', 'Custom', 'Ollama box', 'Custom', 'Custom']);
  });
});
