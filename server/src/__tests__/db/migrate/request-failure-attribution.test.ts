import { afterEach, describe, expect, it } from 'vitest';
import type { Db } from '../../../db/types.js';
import { up, down } from '../../../db/migrations/20261017_233153_request_failure_attribution.js';
import { createEmptyTestDb } from '../../helpers/test-db.js';

// #1347 (PR 1): the migration only adds one column to requests; a minimal
// stand-in table on an EMPTY scratch database is enough to verify the roundtrip.
async function makeDb(): Promise<{ db: Db; cleanup: () => Promise<void> }> {
  const scratch = await createEmptyTestDb();
  await scratch.db.exec(`
    CREATE TABLE requests (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      platform TEXT NOT NULL,
      model_id TEXT NOT NULL,
      key_id BIGINT,
      status TEXT NOT NULL
    );
  `);
  return scratch;
}

async function hasAttributionColumn(db: Db): Promise<boolean> {
  const cols = (await db.all(
    "SELECT column_name FROM information_schema.columns WHERE table_name = 'requests'",
  )) as { column_name: string }[];
  return cols.some((c) => c.column_name === 'failure_attribution');
}

const cleanups: Array<() => Promise<void>> = [];
afterEach(async () => {
  for (const fn of cleanups.splice(0)) await fn();
});

describe('request_failure_attribution migration (#1347 PR 1)', () => {
  it('adds the failure_attribution column', async () => {
    const { db, cleanup } = await makeDb();
    cleanups.push(cleanup);

    expect(await hasAttributionColumn(db)).toBe(false);
    await up(db);
    expect(await hasAttributionColumn(db)).toBe(true);
  });

  it('is idempotent — a second up() is a no-op', async () => {
    const { db, cleanup } = await makeDb();
    cleanups.push(cleanup);

    await up(db);
    await up(db);
    expect(await hasAttributionColumn(db)).toBe(true);
  });

  it('down() drops the column, and up() can add it back (full roundtrip)', async () => {
    const { db, cleanup } = await makeDb();
    cleanups.push(cleanup);

    await up(db);
    await down(db);
    expect(await hasAttributionColumn(db)).toBe(false);

    await up(db);
    expect(await hasAttributionColumn(db)).toBe(true);
  });
});
